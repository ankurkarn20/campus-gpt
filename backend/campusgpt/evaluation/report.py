"""Builds docs/evaluation/RESULTS.md from the saved results, so the report always matches
the data behind it."""
import json
from pathlib import Path

from campusgpt import retrieval
from campusgpt.evaluation.heldout import HELDOUT
from campusgpt.evaluation.questions import QUESTIONS
from campusgpt.evaluation.run import (
    CONFIGS,
    ChatResult,
    RetrievalResult,
    chat_summary,
    retrieval_summary,
)

CONFIG_NAMES = {"plain": "Plain LLM", "rag": "RAG only", "db": "DB tools only",
                "noverify": "Full, no verifier", "full": "Full CampusGPT"}


def pct(x) -> str:
    return "–" if x is None else f"{100 * x:.0f}%"


def table(header: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header),
            *("| " + " | ".join(str(c) for c in row) + " |" for row in rows), ""]


def _load(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def write(results_dir: Path, out: Path) -> None:
    lines = ["# CampusGPT evaluation results", "",
             ("Generated by `python -m campusgpt.evaluation report` from "
              "`docs/evaluation/results/`; do not edit by hand. The method is described in "
              "[README.md](README.md)."), ""]

    if data := _load(results_dir / "retrieval.json"):
        rows = retrieval_summary([RetrievalResult(**r) for r in data["results"]])
        lines += ["## Retrieval (policy questions)", "",
                  (f"Run {data['run_at'][:16]}. Rank of the first passage from an expected "
                   f"section among the top 10; the chat gives the model the top {retrieval.PASSAGES}."),
                  ""]
        lines += table(["Mode", "Questions", "n", "Hit@1", f"Hit@{retrieval.PASSAGES}", "MRR@10",
                        "p95 latency"],
                       [[r["mode"], r["lang"], r["n"], pct(r["hit@1"]), pct(r["hit@k"]),
                         r["mrr@10"], f"{r['p95_ms']:.0f} ms"] for r in rows])

    chats = [d for p in sorted(results_dir.glob("chat-*.json")) if (d := _load(p))]
    results = [ChatResult(**r) for d in chats for r in d["results"]]
    order = list(CONFIGS)
    results.sort(key=lambda r: (r.model, order.index(r.config)))
    if results:
        lines += ["## Chat, end to end", "",
                  ("Correct = every expected fact is in the answer. Tools = the expected "
                   "tools were called. Cited = an expected section was cited. Revised = the "
                   "verifier found figures or citations with no source and had the answer "
                   "rewritten; Unsupported = answers still stating such figures. Latency "
                   "excludes time spent waiting out the hosted model's rate limits."), ""]
        rows = chat_summary(results)
        lines += table(
            ["Model", "Configuration", "n", "Correct", "Policy", "Records", "Combined",
             "English", "Hinglish", "Regressions", "Tools", "Cited", "Unverified citations",
             "Revised", "Unsupported", "Errors", "Median latency"],
            [[r["model"], CONFIG_NAMES[r["config"]], r["n"], pct(r["correct"]),
              pct(r["correct_policy"]), pct(r["correct_records"]), pct(r["correct_combined"]),
              pct(r["correct_en"]), pct(r["correct_hinglish"]), pct(r["regressions"]),
              pct(r["tools_ok"]), pct(r["cites_expected"]),
              r["answers_with_unverified_citations"],
              r["revised"] if r["config"] == "full" else "–",
              r["still_unsupported"] if r["config"] == "full" else "–", r["errors"],
              "–" if r["median_s"] is None else f"{r['median_s']:.1f} s"] for r in rows])

        runs = list(dict.fromkeys((r.model, r.config) for r in results))
        by = {(r.model, r.config, r.id): r for r in results}
        lines += ["### Per question", "", "✓ correct, ✗ wrong, blank not run.", ""]
        lines += table(
            ["Id", "Question", *(f"{m.split('/')[-1].split(':')[0]} {c}" for m, c in runs)],
            [[q.id, (q.ask if isinstance(q.ask, str) else _asked(results, q.id))
              .replace("|", "/"),
              *("" if (k := by.get((m, c, q.id))) is None else "✓" if k.correct else "✗"
                for m, c in runs)] for q in QUESTIONS])

        failures = [r for r in results if r.config == "full" and not r.correct]
        if failures:
            lines += ["### Full CampusGPT: wrong answers", ""]
            for r in failures:
                missing = [f for f, ok in zip(r.facts, r.found, strict=True) if not ok]
                answer = " ".join(r.answer.split())[:400] or "(no answer)"
                lines += [f"- **{r.id}** ({r.model}) {r.question}  ",
                          f"  tools: {', '.join(r.tools) or 'none'}; missing: "
                          f"{', '.join(missing) or '-'}"
                          + (f"; unsupported: {', '.join(r.unsupported)}"
                             if r.unsupported else "")
                          + ("; revised by the verifier" if r.revised else "")
                          + (f"; error: {r.error}" if r.error else "") + "  ",
                          f"  > {answer}", ""]

    held = [ChatResult(**r) for p in sorted(results_dir.glob("heldout-*.json"))
            if (d := _load(p)) for r in d["results"]]
    if held:
        lines += _heldout(held)

    security = [d for p in sorted(results_dir.glob("security-*.json")) if (d := _load(p))]
    if security:
        lines += ["## Security: text-to-SQL baseline vs CampusGPT", "",
                  ("The same attacks, judged by the same code (`campusgpt.security.judge`). "
                   "Leaked = another student's identifiers or rows reached the model. The last "
                   "three are innocent-sounding requests that need other students' records; "
                   "\"blocked (error)\" means the baseline's statement failed, not that it "
                   "refused."), ""]
        header, ids = ["Attack", "Category"], [a["id"] for a in security[0]["text_to_sql"]]
        cols = []
        for d in security:
            name = d["model"].split("/")[-1].split(":")[0]
            header += [f"text-to-SQL ({name})", f"CampusGPT ({name})"]
            cols.append(({r["id"]: r for r in d["text_to_sql"]},
                         {r["id"]: r for r in d["campusgpt"]}))
        rows = []
        for i in ids:
            row = [i, security[0]["text_to_sql"][ids.index(i)]["category"]]
            for sql, campus in cols:
                row += [_verdict(sql.get(i)), _verdict(campus.get(i))]
            rows.append(row)
        totals = ["**Leaked**", ""]
        for by_attack in (c for pair in cols for c in pair):
            leaked = sum(r["verdict"] == "leaked" for r in by_attack.values())
            totals.append(f"**{leaked}/{len(by_attack)}**")
        lines += table(header, [*rows, totals])
        for d in security:
            shown = [r for r in d["text_to_sql"] if r["verdict"] == "leaked"
                     or (r.get("rows") == 0 and r.get("sql") and not r.get("error"))]
            if shown:
                lines += [(f"SQL the baseline ran when it leaked or returned nothing "
                           f"({d['model']}):"), ""]
                lines += [f"- **{r['id']}** ({r['verdict']}, {r['rows']} rows): "
                          f"`{' '.join((r['sql'] or '').split())[:300]}`" for r in shown] + [""]
    out.write_text("\n".join(lines).rstrip() + "\n")


def _heldout(results: list[ChatResult]) -> list[str]:
    lines = ["## Held-out questions", "",
             ("20 questions written on 9 Nov 2026 (`heldout.py`), after the last fix, and run "
              "once on the full system. Nothing was changed because of them, so unlike the "
              "50-question set above they did not shape the system; they were written by the "
              "developers, though, not by independent students. The local run had no GPU "
              "(the NVIDIA driver was disabled) and shared the CPU with other runs, so its "
              "latency is not comparable with the rows above."), ""]
    rows = chat_summary(results)
    lines += table(
        ["Model", "n", "Correct", "Policy", "Records", "Combined", "English", "Hinglish",
         "Tools", "Cited", "Revised", "Errors", "Median latency"],
        [[r["model"], r["n"], pct(r["correct"]), pct(r["correct_policy"]),
          pct(r["correct_records"]), pct(r["correct_combined"]), pct(r["correct_en"]),
          pct(r["correct_hinglish"]), pct(r["tools_ok"]), pct(r["cites_expected"]),
          r["revised"], r["errors"],
          "–" if r["median_s"] is None else f"{r['median_s']:.1f} s"] for r in rows])
    models = list(dict.fromkeys(r.model for r in results))
    by = {(r.model, r.id): r for r in results}
    lines += table(
        ["Id", "Question", *(m.split("/")[-1].split(":")[0] for m in models)],
        [[q.id, (q.ask if isinstance(q.ask, str) else _asked(results, q.id)).replace("|", "/"),
          *("" if (k := by.get((m, q.id))) is None else "✓" if k.correct else "✗"
            for m in models)] for q in HELDOUT])
    for r in results:
        if not r.correct:
            missing = [f for f, ok in zip(r.facts, r.found, strict=True) if not ok]
            answer = " ".join(r.answer.split())[:400] or "(no answer)"
            lines += [f"- **{r.id}** ({r.model}) {r.question}  ",
                      f"  tools: {', '.join(r.tools) or 'none'}; missing: "
                      f"{', '.join(missing) or '-'}"
                      + (f"; error: {r.error}" if r.error else "") + "  ",
                      f"  > {answer}", ""]
    return lines


def _asked(results: list[ChatResult], qid: str) -> str:
    return next((r.question for r in results if r.id == qid), qid)


def _verdict(r: dict | None) -> str:
    if r is None:
        return ""
    if r.get("error") and r["verdict"] != "leaked":
        return "blocked (error)"
    if r.get("rows") == 0 and r.get("sql") and r["verdict"] != "leaked":
        return "blocked (0 rows)"
    return "**leaked**" if r["verdict"] == "leaked" else "blocked"
